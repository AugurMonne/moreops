package jenkins

import (
	"fmt"
)

// PipelineOptions holds options for generating a Jenkinsfile.
type PipelineOptions struct {
	AppName      string
	Environment  string
	AgentLabel   string
	UseDocker    bool
	EphemeralK8s bool
}

// GenerateJenkinsfile produces a declarative Jenkins pipeline script.
func GenerateJenkinsfile(opts PipelineOptions) string {
	agentBlock := "agent any"
	if opts.AgentLabel != "" {
		agentBlock = fmt.Sprintf("agent {\n        node {\n            label '%s'\n        }\n    }", opts.AgentLabel)
	}

	envName := opts.Environment
	if envName == "" {
		envName = "dev"
	}

	return fmt.Sprintf(`// Jenkinsfile generated by MoreOps
pipeline {
    %s

    environment {
        APP_NAME     = '%s'
        ENVIRONMENT  = '%s'
        MOREOPS_ENV  = '%s'
        IMAGE_TAG    = "${env.BUILD_NUMBER}"
    }

    stages {
        stage('Checkout') {
            steps {
                checkout scm
            }
        }

        stage('Build MoreOps CLI') {
            steps {
                sh 'make build'
            }
        }

        stage('Validate Manifests & Policies') {
            steps {
                sh './bin/moreops validate'
            }
        }

        stage('Security Scanning (Trivy)') {
            steps {
                sh './bin/moreops scan fs'
            }
        }

        stage('Ephemeral Cluster Verification') {
            steps {
                sh './bin/moreops test'
            }
        }

        stage('Build & Tag Container') {
            steps {
                sh "docker build -t ${APP_NAME}:${IMAGE_TAG} ."
            }
        }

        stage('MoreOps Dry-Run Plan') {
            steps {
                sh "./bin/moreops plan --env ${ENVIRONMENT}"
            }
        }

        stage('Deploy to Kubernetes') {
            when {
                anyOf {
                    branch 'main'
                    branch 'master'
                }
            }
            steps {
                sh "./bin/moreops apply --yes --env ${ENVIRONMENT}"
            }
        }
    }

    post {
        always {
            cleanWs()
        }
        success {
            echo "✓ Pipeline completed successfully for ${APP_NAME} (${ENVIRONMENT})!"
        }
        failure {
            echo "❌ Pipeline failed! Check logs above."
        }
    }
}
`, agentBlock, opts.AppName, envName, envName)
}
