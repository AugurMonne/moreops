// Module implements Kubernetes workload generation and management (Helm, Kustomize, Manifests).
type Module struct{}

func init() {
	plugin.Register(&Module{})
}

func (m *Module) Name() string {
	return "kubernetes"
}

func (m *Module) Description() string {
	return "Manages Kubernetes manifests, Helm charts, and Kustomize overlays"
}

func (m *Module) Plan(ctx context.Context, cfg *config.Config, envName string) (*plugin.PlanResult, error) {
	if cfg.Modules.Kubernetes == nil || !cfg.Modules.Kubernetes.Enabled {
		return nil, nil
	}

	env, _ := cfg.GetEnvironment(envName)
	namespace := env.Namespace
	if namespace == "" {
		namespace = "default"
	}

	k8sCfg := cfg.Modules.Kubernetes
	appName := cfg.Project.Name
	port := k8sCfg.Port
	if port <= 0 {
		port = 8080
	}
	replicas := k8sCfg.Replicas
	if replicas <= 0 {
		replicas = 2
	}

	image := appName + ":latest"
	if cfg.Modules.Containers != nil && cfg.Modules.Containers.Image != "" {
		image = cfg.Modules.Containers.Image
	}

	res := &plugin.PlanResult{
		ModuleName:  m.Name(),
		FileChanges: make([]diff.FileChange, 0),
		Summary:     fmt.Sprintf("Kubernetes %s configuration for %s", k8sCfg.Tool, appName),
	}

	hpaEnabled := true
	minReplicas := replicas
	maxReplicas := 10
	cpuTarget := 80
	if k8sCfg.Autoscaling != nil {
		hpaEnabled = k8sCfg.Autoscaling.Enabled
		if k8sCfg.Autoscaling.MinReplicas > 0 {
			minReplicas = k8sCfg.Autoscaling.MinReplicas
		}
		if k8sCfg.Autoscaling.MaxReplicas > 0 {
			maxReplicas = k8sCfg.Autoscaling.MaxReplicas
		}
		if k8sCfg.Autoscaling.CPUPercentage > 0 {
			cpuTarget = k8sCfg.Autoscaling.CPUPercentage
		}
	}

	switch k8sCfg.Tool {
	case "helm":
		changes, err := generateHelmChart(appName, namespace, image, port, replicas, k8sCfg.Ingress, hpaEnabled, minReplicas, maxReplicas, cpuTarget, cfg.Modules.Database, cfg.Modules.Messaging)
		if err != nil {
			return nil, err
		}
		res.FileChanges = append(res.FileChanges, changes...)

	case "kustomize":
		changes, err := generateKustomize(appName, namespace, image, port, replicas, k8sCfg.Ingress, envName)
		if err != nil {
			return nil, err
		}
		res.FileChanges = append(res.FileChanges, changes...)

	default: // "manifests"
		changes, err := generateRawManifests(appName, namespace, image, port, replicas, k8sCfg.Ingress, envName)
		if err != nil {
			return nil, err
		}
		res.FileChanges = append(res.FileChanges, changes...)
	}

	return res, nil
}

func (m *Module) Apply(ctx context.Context, plan *plugin.PlanResult) error {
	return plugin.ExecutePlan(plan)
}

